// bun run hero:assets [--check] [--inventory] [--update-budget] [--src dir] [--out dir]
//   (default)        rebuild the captures, prove them identical, write assets + manifest.json + report.json to the output folder
//   --check          same work in memory, writes nothing; fails when the output folder (if present) differs from what the sources
//                    give, or when the byte budget (budget.json, +3 %) is exceeded; for the CI
//   --inventory      JSON inventory of the raw captures, nothing else
//   --budget file    use another budget file (tests)
//   --update-budget  rewrite the baselines of budget.json from this run (a deliberate act, reviewed in the PR)
import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises'
import { join, resolve } from 'node:path'
import { brotliDecompressSync, gunzipSync } from 'node:zlib'
import { budgetMetrics, checkBudget } from './budget.mjs'
import { sha256 } from './equivalence.mjs'
import { inventoryOfAll } from './inventory.mjs'
import { runPipeline } from './pipeline.mjs'
import { realTools } from './tools.mjs'

const root = resolve(import.meta.dirname, '..', '..')
const here = import.meta.dirname

const readJson = async file => JSON.parse(await readFile(file, 'utf8'))

async function readSources(config, directory) {
	const entries = await Promise.all(
		config.captures.map(async capture => [
			capture.name,
			new Uint8Array(await readFile(join(directory, `${capture.name}.glb`))),
		])
	)
	return Object.fromEntries(entries)
}

const DECOMPRESSORS = { '.br': brotliDecompressSync, '.gz': gunzipSync }

/** A `.gz` or `.br` copy is right when it decompresses to the payload (other levels and zlib versions give other bytes); anything else must match byte for byte. */
function same(name, onDisk, outputs) {
	const decompress = DECOMPRESSORS[name.slice(-3)]
	if (!decompress) return sha256(onDisk) === sha256(outputs.get(name))
	try {
		return sha256(decompress(onDisk)) === sha256(outputs.get(name.slice(0, -3)))
	} catch {
		return false
	}
}

/** Differences between what the pipeline produces and what is on disk. */
export async function diffOutputs(outputs, directory) {
	let present
	try {
		present = await readdir(directory)
	} catch {
		return null
	}
	const results = await Promise.all(
		[...outputs].map(async ([name]) => {
			try {
				const onDisk = await readFile(join(directory, name))
				return same(name, onDisk, outputs) ? null : `${name}: differs from the regenerated file`
			} catch {
				return `${name}: missing`
			}
		})
	)
	const stale = present.filter(name => !outputs.has(name)).map(name => `${name}: not produced by the sources (stale)`)
	return [...results.filter(Boolean), ...stale]
}

const kb = bytes => `${(bytes / 1024).toFixed(1)} KiB`

function printReport(report, budget) {
	console.log('\ncapture        raw GLB  ->  shipped (raw / gzip / brotli)')
	for (const [name, entry] of Object.entries(report.files))
		console.log(
			`${name.padEnd(12)} ${kb(entry.source.bytes).padStart(10)}  ->  ${entry.kind.padEnd(5)} ${kb(entry.bytes.raw).padStart(10)} / ${kb(entry.bytes.gzip).padStart(9)} / ${kb(entry.bytes.brotli).padStart(9)}  ${entry.file}`
		)
	console.log('\nbudget (bytes, brotli unless stated)')
	for (const row of budget.rows)
		console.log(
			`${row.ok ? 'ok  ' : 'FAIL'} ${row.metric.padEnd(18)} ${String(row.actual).padStart(9)}  (baseline ${row.baseline}, limit ${row.limit})`
		)
	for (const metric of budget.unbudgeted) console.log(`FAIL ${metric}: no baseline in budget.json`)
}

/** @param {string[]} argv @returns {Promise<number>} exit code */
export async function main(argv) {
	const flag = name => argv.includes(name)
	const option = name => (argv.includes(name) ? argv[argv.indexOf(name) + 1] : undefined)
	const config = await readJson(join(here, 'config.json'))
	const sourceDir = resolve(root, option('--src') ?? config.sourceDir)
	const outputDir = resolve(root, option('--out') ?? config.outputDir)
	const budgetFile = resolve(root, option('--budget') ?? join(here, 'budget.json'))
	const sources = await readSources(config, sourceDir)
	if (flag('--inventory')) {
		console.log(JSON.stringify(inventoryOfAll(sources), null, '\t'))
		return 0
	}
	const tools = await realTools()
	const { outputs, report } = await runPipeline(config, sources, tools, line => console.log(line))
	if (flag('--update-budget')) {
		const budget = await readJson(budgetFile)
		budget.baseline = budgetMetrics(report)
		await writeFile(budgetFile, `${JSON.stringify(budget, null, '\t')}\n`)
		console.log(`budget.json updated: ${JSON.stringify(budget.baseline)}`)
		return 0
	}
	const budget = checkBudget(report, await readJson(budgetFile))
	printReport(report, budget)
	if (flag('--check')) {
		const problems = await diffOutputs(outputs, outputDir)
		if (problems === null)
			console.log(`\n${outputDir} does not exist: nothing to compare (it is generated by the web build).`)
		else if (problems.length > 0)
			console.log(`\nGenerated assets do not match the sources:\n${problems.map(line => `  ${line}`).join('\n')}`)
		else console.log('\nGenerated assets match the sources.')
		return budget.ok && !problems?.length ? 0 : 1
	}
	if (!budget.ok) return 1
	await rm(outputDir, { recursive: true, force: true })
	await mkdir(outputDir, { recursive: true })
	await Promise.all([...outputs].map(([name, bytes]) => writeFile(join(outputDir, name), bytes)))
	console.log(`\n${outputs.size} files written to ${outputDir}`)
	return 0
}

if (process.argv[1] && resolve(process.argv[1]) === import.meta.filename)
	process.exitCode = await main(process.argv.slice(2))
