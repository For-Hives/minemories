import { useEffect, useLayoutEffect, useMemo } from 'react'
import charterCss from '../hero/charter.css?raw'
import filmCss from '../hero/film.css?raw'
import { prepareRoot } from '../hero/first-paint.js'
import tokensCss from '../hero/tokens.css?raw'
import { useI18n } from '../i18n/I18n'
import { createGlbFetcher, loadCaptureManifest } from '../lib/capture-delta'
import { createHeroI18n } from '../lib/hero-i18n'
import { observeReveal } from '../lib/reveal'
import { reportWebFailure } from '../observability/WebObservability'
import { HeroMarkup } from './HeroMarkup'

/** Folder of the GLB captures (static files, apps/web/public/hero/captures). */
/** Jetons de la charte, kit du jeu, composants de la charte : dans cet ordre (docs/features/design-system.md). */
const styles = [tokensCss, filmCss, charterCss].join('\n')
export const capturesUrl = '/hero/captures/'
/**
 * Optimised copies of the captures (content-hashed base + deltas, `manifest.json`), generated by `bun run hero:assets`
 * (docs/features/film-assets-pipeline.md). Absent in development until the command has run: the film then uses the plain files above.
 */
export const captureAssetsUrl = '/hero/captures-opt/'
/** Inline script of the prerendered `/` (scripts/prerender-web.mjs puts it before the app's markup): the phase, the layout variables and the film class are on <html> before the page is drawn. */
export const firstPaintScript = `(${prepareRoot.toString()})(document.documentElement, location)`

/**
 * The home page's film: a Three.js scene driven by the scroll, the game's own interface over it, then the site. Everything is client-only: the prerender holds the markup
 * (and so the story in words and the whole site), the film code is a separate chunk loaded after the first render, and without WebGL the site stays as the page.
 * The film's CSS is global (it styles <html>, <body>, main...): it lives in a <style> of this component, so it exists only while the home page does.
 */
export function HeroFilm() {
	const { locale } = useI18n()
	const i18n = useMemo(() => createHeroI18n(locale), [])
	useLayoutEffect(() => prepareRoot(document.documentElement, window.location), [])
	useEffect(() => {
		let cancelled = false
		let dispose: (() => void) | undefined
		// The manifest is requested now, alongside the film's chunk, so that the first capture does not wait for it.
		const assets = new URL(captureAssetsUrl, window.location.href)
		const fetchGlb = createGlbFetcher({
			manifest: loadCaptureManifest(new URL('manifest.json', assets)),
			assets,
			subtle: globalThis.crypto?.subtle,
		})
		import('../hero/hero.js')
			.then(({ mountHero }) => {
				if (cancelled) return
				dispose = mountHero({ i18n, capturesUrl, fetchGlb })
				// test hook: how many captures fell back to the full GLB files (the identity harness expects 0)
				const hero = (window as { __hero?: Record<string, unknown> }).__hero
				if (hero) hero.captureFallbacks = fetchGlb.stats
			})
			.catch(() => reportWebFailure('page-render'))
		return () => {
			cancelled = true
			dispose?.()
		}
	}, [i18n])
	useEffect(() => {
		const site = document.getElementById('site')
		if (!site) return
		const reduced =
			Boolean(window.matchMedia?.('(prefers-reduced-motion: reduce)').matches) ||
			document.documentElement.dataset.mcMotion === 'reduced'
		return observeReveal(site, { reduced })
	}, [])
	useEffect(() => i18n.set(locale), [i18n, locale])
	return (
		<>
			<style dangerouslySetInnerHTML={{ __html: styles }} />
			<HeroMarkup />
		</>
	)
}
