// @vitest-environment jsdom
import * as THREE from 'three'
import { expect, test, vi } from 'vitest'
import { ViewerNavigation } from './viewer-navigation'

test('first person moves at walking speed, clamps stalled frames, and releases keys on blur', () => {
	const canvas = document.createElement('canvas')
	document.body.append(canvas)
	const camera = new THREE.PerspectiveCamera()
	const navigation = new ViewerNavigation(camera, canvas)
	const key = (type: string, code: string) =>
		canvas.dispatchEvent(new KeyboardEvent(type, { code, bubbles: true, cancelable: true }))
	navigation.setActive(true)
	expect(document.activeElement).toBe(canvas)
	key('keydown', 'KeyW')
	navigation.update(10)
	expect(camera.position.z).toBeCloseTo(-0.15)
	key('keydown', 'AltLeft')
	navigation.update(0.05)
	expect(camera.position.z).toBeCloseTo(-0.185)
	canvas.dispatchEvent(new Event('blur'))
	navigation.update(0.05)
	expect(camera.position.z).toBeCloseTo(-0.185)
	key('keydown', 'Space')
	key('keydown', 'ShiftLeft')
	navigation.update(0.05)
	expect(camera.position.y).toBeCloseTo(0.6)
	key('keyup', 'Space')
	navigation.setActive(false)
	key('keydown', 'KeyW')
	navigation.update(0.05)
	expect(camera.position.z).toBeCloseTo(-0.185)
	navigation.dispose()
	canvas.remove()
})

test('touch controls stop on release and dragging looks around without moving the camera', () => {
	const canvas = document.createElement('canvas')
	canvas.setPointerCapture = vi.fn()
	const camera = new THREE.PerspectiveCamera()
	const navigation = new ViewerNavigation(camera, canvas)
	navigation.setActive(true)
	navigation.move('forward', true)
	navigation.update(0.05)
	navigation.move('forward', false)
	const position = camera.position.clone()
	canvas.dispatchEvent(new MouseEvent('pointerdown', { button: 0 }))
	const move = new MouseEvent('pointermove', { clientX: 100, clientY: 10000 })
	Object.defineProperties(move, { movementX: { value: 100 }, movementY: { value: 10000 } })
	canvas.dispatchEvent(move)
	expect(camera.quaternion.y).not.toBe(0)
	expect(camera.position.equals(position)).toBe(true)
	canvas.dispatchEvent(new Event('pointerup'))
	navigation.update(0.05)
	expect(camera.position.equals(position)).toBe(true)
	navigation.dispose()
})
